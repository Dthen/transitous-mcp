"""T2 cancellation, walking-failure and realtime tests (§4.13, §2.6).

The rule under test is the whole-itinerary one: a place that is an endpoint of a
dummy walk *anywhere* in the itinerary never reports ``stop_cancelled: true``,
because the payload's flag in that context was generated by the failed street
path. Every place of the rendered itinerary is asserted, not only the walking leg.
"""

import json
import os
import sys

import pytest

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import fixture_support

from transit_core import errors, places, plan

AYR_NCL_COORD = {
    "from_lat": 55.458267,
    "from_lon": -4.625827,
    "to_lat": 54.968338,
    "to_lon": -1.616046,
    "time": "2026-10-27T09:00:00Z",
    "transit_modes": ["RAIL"],
}

NCL_AYR = {
    "from_lat": 54.968338,
    "from_lon": -1.616046,
    "to_lat": 55.458267,
    "to_lon": -4.625827,
    "time": "2026-10-27T22:15:00Z",
    "num_itineraries": 3,
    "transit_modes": ["RAIL"],
}

STREET_LEG_FIELDS = ("walking_route_unavailable", "duration_is_estimate", "cancelled")


class StubResponse:
    def __init__(self, body):
        self.status = 200
        self._body = body

    def read(self):
        return self._body

    def close(self):
        pass


class Transport:
    def __init__(self, payload):
        self.payload = payload if isinstance(payload, bytes) else json.dumps(payload).encode()
        self.urls = []

    def __call__(self, request, timeout):
        self.urls.append(request.full_url)
        return StubResponse(self.payload)


def run(args, fixture=None, body=None):
    transport = Transport(fixture_support.read_bytes(fixture) if fixture else body)
    result = plan.plan(args, transport=transport)
    assert result["outcome"] == "ok", result
    return result


def first(result):
    return result["itineraries"][0]


def every_place(itinerary):
    for leg in itinerary["legs"]:
        yield leg["index"], "from", leg["from"]
        yield leg["index"], "to", leg["to"]


def codes(result):
    return [warning["code"] for warning in result["warnings"]]


# ── the dummy-walk predicate as rendered ───────────────────────────


def test_both_dummy_walks_are_labelled_as_estimates():
    result = run(AYR_NCL_COORD, fixture="synthetic_plan_ayr_ncl_coord.json")
    legs = first(result)["legs"]
    assert legs[0]["mode"] == "WALK" and legs[0]["walking_route_unavailable"] is True
    assert legs[0]["duration_is_estimate"] is True
    assert legs[0]["cancelled"] is None
    assert legs[0]["note"]
    assert legs[2]["walking_route_unavailable"] is True
    assert legs[2]["duration_is_estimate"] is True
    # the empty points string is what proves the dummy, not an empty object
    assert legs[0]["geometry_present"] is False
    assert legs[2]["geometry_present"] is False


def test_a_routed_street_leg_is_not_a_dummy_walk():
    result = run(AYR_NCL_COORD, fixture="synthetic_plan_ayr_ncl_coord.json")
    legs = first(result)["legs"]
    routed = legs[4]
    assert routed["mode"] == "WALK"
    assert routed["walking_route_unavailable"] is False
    assert routed["duration_is_estimate"] is False
    assert routed["cancelled"] is None
    assert routed["geometry_present"] is True
    assert routed["note"] is None


def test_transit_legs_never_report_a_walking_failure():
    result = run(AYR_NCL_COORD, fixture="synthetic_plan_ayr_ncl_coord.json")
    for leg in first(result)["legs"]:
        if leg["mode"] != "WALK":
            assert leg["walking_route_unavailable"] is False
            assert leg["duration_is_estimate"] is False
            assert leg["cancelled"] is False


# ── whole-itinerary place attribution ──────────────────────────────


def test_no_place_in_a_dummy_walk_itinerary_is_reported_as_a_cancelled_stop():
    result = run(AYR_NCL_COORD, fixture="synthetic_plan_ayr_ncl_coord.json")
    for itinerary in result["itineraries"]:
        for index, side, place in every_place(itinerary):
            assert place["stop_cancelled"] is not True, (itinerary["option"], index, side, place)


def test_dummy_endpoints_keep_their_raw_flag_and_provenance():
    result = run(AYR_NCL_COORD, fixture="synthetic_plan_ayr_ncl_coord.json")
    itinerary = first(result)
    ayr = itinerary["legs"][0]["to"]
    assert ayr["name"] == "Ayr"
    assert ayr["stop_cancelled"] is None
    assert ayr["source_cancelled"] is True
    assert ayr["source_cancelled_origin"] == "walking_route_unavailable"
    glasgow = itinerary["legs"][2]["from"]
    assert glasgow["stop_cancelled"] is None
    assert glasgow["source_cancelled_origin"] == "walking_route_unavailable"


def test_an_explicitly_uncancelled_place_stays_false():
    result = run(AYR_NCL_COORD, fixture="synthetic_plan_ayr_ncl_coord.json")
    itinerary = first(result)
    # Ayr appears both ways in the fixture itinerary: flagged by the dummy walk,
    # and explicitly not cancelled as the origin of the first service leg.
    assert itinerary["legs"][0]["to"]["stop_cancelled"] is None
    assert itinerary["legs"][1]["from"]["stop_cancelled"] is False
    assert itinerary["legs"][1]["from"]["source_cancelled"] is False
    assert itinerary["legs"][1]["from"]["source_cancelled_origin"] is None


def test_a_cancelled_place_elsewhere_on_a_dummy_route_is_not_blamed_on_the_service():
    """The discriminating case for whole-itinerary attribution.

    Labelled in-memory mutation of the fixture body: the Glasgow Central place of
    a *service* leg carries ``cancelled: true``, and the same place is an endpoint of
    the itinerary's dummy walk. Per-leg attribution would report ``service`` here;
    the itinerary-wide rule reports the walking failure instead.
    """
    body = fixture_support.load("synthetic_plan_ayr_ncl_coord.json")
    itinerary = body["itineraries"][0]
    service_leg = itinerary["legs"][3]
    assert service_leg["mode"] == "REGIONAL_RAIL"
    service_leg["from"]["cancelled"] = True  # same stop as the dummy-walk endpoint
    result = run(dict(AYR_NCL_COORD), body=body)
    mutated = first(result)
    place = mutated["legs"][3]["from"]
    assert place["name"] == "Glasgow Central"
    assert place["stop_cancelled"] is None
    assert place["source_cancelled"] is True
    assert place["source_cancelled_origin"] == "walking_route_unavailable"
    # and the same place, mapped at the dummy leg, still reports the same origin
    assert mutated["legs"][2]["to"]["source_cancelled_origin"] == "walking_route_unavailable"


def test_a_dummy_walk_endpoint_does_not_cancel_the_other_legs_places():
    body = fixture_support.load("synthetic_plan_ayr_ncl_coord.json")
    itinerary = body["itineraries"][0]
    itinerary["legs"][5]["to"]["cancelled"] = True  # Newcastle, not a dummy endpoint
    result = run(dict(AYR_NCL_COORD), body=body)
    place = first(result)["legs"][5]["to"]
    assert place["name"] == "Newcastle"
    assert place["stop_cancelled"] is True
    assert place["source_cancelled_origin"] == "service"


def test_the_reverse_overnight_itinerary_has_no_false_service_cancellation():
    result = run(NCL_AYR, fixture="synthetic_plan_ncl_ayr_depart.json")
    for itinerary in result["itineraries"]:
        for index, side, place in every_place(itinerary):
            if place["stop_cancelled"] is True:
                # only a genuinely service-cancelled place may say so; this fixture
                # contains none, so any True is a mapping defect
                raise AssertionError((itinerary["option"], index, side, place))
    itinerary = first(result)
    assert itinerary["legs"][4]["walking_route_unavailable"] is True
    assert itinerary["legs"][6]["walking_route_unavailable"] is True
    # The same stop appears twice: as an explicitly uncancelled arrival of the
    # service leg, and as the origin of the final dummy walk. The explicit false
    # stays false; the dummy-endpoint occurrence keeps its raw flag with provenance.
    ayr_arrival = itinerary["legs"][5]["to"]
    ayr_walk_origin = itinerary["legs"][6]["from"]
    assert ayr_arrival["stop_id"] == ayr_walk_origin["stop_id"]
    assert ayr_arrival["name"] == "Ayr"
    assert ayr_arrival["stop_cancelled"] is False
    assert ayr_walk_origin["stop_cancelled"] is None
    assert ayr_walk_origin["source_cancelled"] is True
    assert ayr_walk_origin["source_cancelled_origin"] == "walking_route_unavailable"


def test_place_tri_state_exactly_mirrors_the_payload():
    result = run(AYR_NCL_COORD, fixture="synthetic_plan_ayr_ncl_coord.json")
    places_by_name = {}
    for _, _, place in every_place(first(result)):
        places_by_name.setdefault(place["name"], []).append(place)
    # §4.5.2 substitutes the requested coordinate string for the START/END sentinel
    for place in places_by_name["54.968338,-1.616046"]:
        assert place["stop_cancelled"] is None
        assert place["source_cancelled"] is None
        assert place["source_cancelled_origin"] is None
    # the origin sentinel is a dummy-walk endpoint and carries the raw flag
    for place in places_by_name["55.458267,-4.625827"]:
        assert place["source_cancelled"] is True
        assert place["stop_cancelled"] is None



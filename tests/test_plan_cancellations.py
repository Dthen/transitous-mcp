# ── the shared stop-time mapper's tri-state (consumed by the boards) ──


def test_stop_time_cancellation_tri_state_is_the_shared_mapper_contract():
    """§9.1 lists trip-cancelled stop-times under the plan cancellation suite.

    The rendering belongs to the boards slice; this pins the shared mapper's
    tri-state on the retained synthetic body so a plan regression cannot quietly
    change the mapping T4 consumes.
    """
    body = fixture_support.load("synthetic_trip_cancelled_stoptime.json")
    mapped = [places.map_stop_time_cancellation(stop_time) for stop_time in body["stopTimes"]]
    assert [(item["stop_cancelled"], item["trip_cancelled"]) for item in mapped] == [
        (True, True),
        (True, False),
        (False, False),
    ]


def test_absent_tri_state_members_map_to_null_and_are_never_invented():
    body = fixture_support.load("synthetic_trip_cancelled_stoptime.json")
    stop_time = dict(body["stopTimes"][2])
    stop_time.pop("cancelled")
    stop_time.pop("tripCancelled")
    assert places.map_stop_time_cancellation(stop_time) == {
        "stop_cancelled": None,
        "trip_cancelled": None,
    }


def test_a_leg_without_realtime_members_is_null_not_false():
    body = fixture_support.load("synthetic_plan_ayr_ncl_coord.json")
    leg = body["itineraries"][0]["legs"][1]
    leg.pop("realTime")
    leg.pop("scheduled")
    result = run(dict(AYR_NCL_COORD), body=body)
    mapped = first(result)["legs"][1]
    assert mapped["realtime"] is None
    assert mapped["scheduled"] is None
    # an absence is not evidence of a scheduled service at the itinerary level either
    assert first(result)["realtime_present"] is False
